function pretty_name(s) {
   const parts = String(s).split(/[^A-Za-z0-9]+/).filter((p) => p.length > 0)
    if (parts.length === 0) return '';
   let out = parts[0]
   for (let i = 1; i < parts.length; i++) out += parts[i].charAt(0).toUpperCase() + parts[i].slice(1)
	return out
}

