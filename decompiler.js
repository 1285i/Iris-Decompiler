			let d = 1, close = -1;
            for (let k = j + 1; k <= endIdx; k++) {
            const t = trim(lines[k])
        if (/^(function\b|local function\b|if\b|for\b|while\b|repeat\b)/.test(t) || /\bdo$/.test(t)) d++
            else if (/^end\b/.test(t) || /^until\b/.test(t)) { d--; if (d === 0) { close = k; break } }
            }
