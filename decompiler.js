			const var_name = t.slice(nameStart, nameEnd);


            if (var_name.charAt(0) === "_") continue
         const kws = ['and', 'break', 'do', "else", 'elseif', "end", "false", 'for', "function", 'if',
                'in', "local", "nil", 'not', "or", "repeat", 'return', 'then', 'true', "until", "while", 'continue']
